_CANONICAL = {key for _, keys in SECTIONS for key in keys}

#: GROMACS compares mdp option names with the separators removed entirely, so
#: ``vdw_type``, ``vdw-type`` and ``vdwtype`` are one option. Mapping a key back
#: to the spelling used in SECTIONS is what keeps a hand-written file from
#: landing half of its options under "other" when it is read and rewritten.
_BY_SQUASHED = {key.replace("-", ""): key for key in _CANONICAL}


def _norm(key: str) -> str:
    """GROMACS treats ``-`` and ``_`` in mdp keys as identical; we prefer ``-``."""
    key = key.strip().lower().replace("_", "-")
    return _BY_SQUASHED.get(key.replace("-", ""), key)


def render_mdp(options: Dict[str, object], title: str = "") -> str:
    normalised = {}
    for key, value in options.items():
        if value is None:
            continue
        normalised[_norm(key)] = value

    lines: List[str] = []
    if title:
        lines += [f"; {title}", "; generated by Comfy-gmx", ""]

    used = set()
    for section, keys in SECTIONS:
        present = [k for k in keys if k in normalised]
        if not present:
            continue
        lines.append(f"; ---- {section} " + "-" * max(0, 48 - len(section)))
        width = max(len(k) for k in present)
        for key in present:
            lines.append(f"{key.ljust(width)} = {normalised[key]}")
            used.add(key)
        lines.append("")

    leftover = [k for k in normalised if k not in used]
    if leftover:
        lines.append("; ---- Other " + "-" * 48)
        width = max(len(k) for k in leftover)
        for key in leftover:
            lines.append(f"{key.ljust(width)} = {normalised[key]}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def parse_mdp(text: str) -> Dict[str, str]:
    """Read an mdp file into a dict, dropping comments."""
    out: Dict[str, str] = {}
    for raw in text.splitlines():
        line = raw.split(";", 1)[0].strip()
        if not line or "=" not in line:
            continue
        key, value = line.split("=", 1)
        out[_norm(key)] = value.strip()
    return out


def merge_extra(options: Dict[str, object], extra_text: str) -> Dict[str, object]:
    """Overlay free-text ``key = value`` lines on top of a preset."""
    merged = dict(options)
    merged.update(parse_mdp(extra_text or ""))
    return merged


