"""MDP presets and rendering.

Presets are plain ``{option: value}`` dictionaries so a node can start from one
and then override individual keys from its widgets.  :func:`render_mdp` writes
them back out grouped under section headers, which makes a generated file
readable enough to hand to a collaborator.
"""

